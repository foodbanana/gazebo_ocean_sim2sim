#!/usr/bin/env python3
"""config/simple_drone.yaml -> models/simple_drone/model.sdf (one rigid body).

Same shapes, positions and masses as the Isaac Sim drone (data_collection_ur5_gripper
isaacsim/scripts/build_simple_drone.py): body box + 4 x (arm box, motor cylinder, rotor disc, leg).
Every shape is both visual and collision. The link inertia is the sum of the shapes
(each a uniform solid with its own mass) about the body origin.

The model also has a DetachableJoint that holds it on a static anchor model (world-fixed hover):
  attach: gz topic /drone/attach (gz.msgs.Empty), detach: /drone/detach, state: /drone/state.

Run from anywhere:  python3 ocean_sim2sim_gazebo/scripts/build_simple_drone.py
"""
import math
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
CORNERS = ((1, 1), (-1, 1), (-1, -1), (1, -1))   # front-left, back-left, back-right, front-right (as Isaac Sim)


def box_inertia(m, sx, sy, sz):
    return [m * (sy ** 2 + sz ** 2) / 12, m * (sx ** 2 + sz ** 2) / 12, m * (sx ** 2 + sy ** 2) / 12]


def cyl_inertia(m, r, h):   # axis z
    return [m * (3 * r ** 2 + h ** 2) / 12, m * (3 * r ** 2 + h ** 2) / 12, m * r ** 2 / 2]


def rotate_z(I, yaw):
    """Diagonal inertia [ixx, iyy, izz] rotated about z -> (ixx, iyy, izz, ixy)."""
    c, s = math.cos(yaw), math.sin(yaw)
    ixx = c * c * I[0] + s * s * I[1]
    iyy = s * s * I[0] + c * c * I[1]
    ixy = c * s * (I[0] - I[1])
    return ixx, iyy, I[2], ixy


def build(c):
    L, W, H = c['body']['size']
    a, m, r, lg = c['arms'], c['motors'], c['rotors'], c['legs']
    if a['motor_x'] <= L / 2 - a['inset'] or a['motor_y'] <= W / 2:
        raise SystemExit('motors must be outside the body')
    body_mass = c['mass'] - 4 * (a['mass'] + m['mass'] + r['mass'] + lg['mass'])
    if body_mass <= 0:
        raise SystemExit(f'body mass <= 0: {body_mass}')
    rotor_z = a['z'] + m['height'] + r['gap'] + r['thickness'] / 2
    leg_top, leg_bot = a['z'] - a['thickness'] / 2, -H / 2 - lg['clearance']

    shapes = [('body', 'box', (L, W, H), (0, 0, 0), 0.0, body_mass, c['body']['color'])]
    for i, (sx, sy) in enumerate(CORNERS):
        x0, y0 = sx * (L / 2 - a['inset']), sy * W / 2
        x1, y1 = sx * a['motor_x'], sy * a['motor_y']
        length = math.hypot(x1 - x0, y1 - y0)
        yaw = math.atan2(y1 - y0, x1 - x0)
        shapes += [
            (f'arm{i}', 'box', (length, a['width'], a['thickness']), ((x0 + x1) / 2, (y0 + y1) / 2, a['z']), yaw, a['mass'], a['color']),
            (f'motor{i}', 'cyl', (m['radius'], m['height']), (x1, y1, a['z'] + m['height'] / 2), 0.0, m['mass'], m['color']),
            (f'rotor{i}', 'cyl', (r['radius'], r['thickness']), (x1, y1, rotor_z), 0.0, r['mass'], r['color']),
            (f'leg{i}', 'cyl', (lg['radius'], leg_top - leg_bot), (x1, y1, (leg_top + leg_bot) / 2), 0.0, lg['mass'], lg['color']),
        ]

    # composite inertia about the body origin (centre of mass may be off the origin: parallel axis to the COM)
    M = sum(s[5] for s in shapes)
    com = [sum(s[5] * s[3][k] for s in shapes) / M for k in range(3)]
    ixx = iyy = izz = ixy = ixz = iyz = 0.0
    for name, kind, dim, pos, yaw, mass, _ in shapes:
        I = box_inertia(mass, *dim) if kind == 'box' else cyl_inertia(mass, *dim)
        jxx, jyy, jzz, jxy = rotate_z(I, yaw)
        d = [pos[k] - com[k] for k in range(3)]
        ixx += jxx + mass * (d[1] ** 2 + d[2] ** 2)
        iyy += jyy + mass * (d[0] ** 2 + d[2] ** 2)
        izz += jzz + mass * (d[0] ** 2 + d[1] ** 2)
        ixy += jxy - mass * d[0] * d[1]
        ixz += -mass * d[0] * d[2]
        iyz += -mass * d[1] * d[2]

    def geom(kind, dim):
        if kind == 'box':
            return f'<box><size>{dim[0]:.6f} {dim[1]:.6f} {dim[2]:.6f}</size></box>'
        return f'<cylinder><radius>{dim[0]:.6f}</radius><length>{dim[1]:.6f}</length></cylinder>'

    parts = []
    for name, kind, dim, pos, yaw, mass, color in shapes:
        pose = f'{pos[0]:.6f} {pos[1]:.6f} {pos[2]:.6f} 0 0 {yaw:.6f}'
        rgb = ' '.join(f'{v:g}' for v in color)
        parts.append(f'''      <collision name="{name}_collision">
        <pose>{pose}</pose>
        <geometry>{geom(kind, dim)}</geometry>
      </collision>
      <visual name="{name}_visual">
        <pose>{pose}</pose>
        <geometry>{geom(kind, dim)}</geometry>
        <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse></material>
      </visual>''')

    sdf = f'''<?xml version="1.0"?>
<!-- Generated by ocean_sim2sim_gazebo/scripts/build_simple_drone.py from config/simple_drone.yaml. Do not edit. -->
<sdf version="1.9">
  <model name="simple_drone">
    <link name="body">
      <inertial>
        <pose>{com[0]:.6f} {com[1]:.6f} {com[2]:.6f} 0 0 0</pose>
        <mass>{M:.6f}</mass>
        <inertia>
          <ixx>{ixx:.6e}</ixx><ixy>{ixy:.6e}</ixy><ixz>{ixz:.6e}</ixz>
          <iyy>{iyy:.6e}</iyy><iyz>{iyz:.6e}</iyz><izz>{izz:.6e}</izz>
        </inertia>
      </inertial>
{chr(10).join(parts)}
    </link>

    <!-- world-fixed hover: hold the body on the static model "drone_anchor" until /drone/detach -->
    <plugin filename="gz-sim-detachable-joint-system" name="gz::sim::systems::DetachableJoint">
      <parent_link>body</parent_link>
      <child_model>drone_anchor</child_model>
      <child_link>link</child_link>
      <attach_topic>/drone/attach</attach_topic>
      <detach_topic>/drone/detach</detach_topic>
      <output_topic>/drone/state</output_topic>
    </plugin>
  </model>
</sdf>
'''
    return sdf, body_mass, M, rotor_z, leg_bot, com


def main():
    with open(os.path.join(PKG, 'config', 'simple_drone.yaml')) as f:
        c = yaml.safe_load(f)
    sdf, body_mass, M, rotor_z, leg_bot, com = build(c)
    out = os.path.join(PKG, 'models', 'simple_drone', 'model.sdf')
    with open(out, 'w') as f:
        f.write(sdf)
    L, W, H = c['body']['size']
    print(f'[OK] {out}')
    print(f'  body {L * 1000:.0f} x {W * 1000:.0f} x {H * 1000:.0f} mm, {body_mass:.3f} kg / total {M:.3f} kg, '
          f'COM ({com[0] * 1000:.1f}, {com[1] * 1000:.1f}, {com[2] * 1000:.1f}) mm')
    print(f'  rotor discs at z {rotor_z * 1000:.0f} mm, leg ends at z {leg_bot * 1000:.0f} mm')


if __name__ == '__main__':
    main()
