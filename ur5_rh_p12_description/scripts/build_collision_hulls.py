#!/usr/bin/env python3
"""Collision meshes as Isaac Sim uses them -> meshes/collision_convex/ + config/ur5_visual_parameters_convex.yaml.

Isaac Sim (PhysX) does not collide with the raw triangle meshes of moving links. The imported robot USD sets
physics:approximation = "convexHull" on every mesh collider (data_collection_ur5_gripper
isaacsim/assets/robots/ur5_rh_p12_d435i/payloads/instances.usda), and the scene layer replaces the forearm with a
convex decomposition (isaacsim/config/drive_gains.yaml collision_shapes: 32 hulls, 64 vertices, error 2 %).
Gazebo (DART + Bullet) uses the mesh as given, so the same shapes are made here:

    gripper base, r1, r2, l1, l2, wrist mount collision plate,
    UR5 base, shoulder, upper arm, wrist 1-3        -> convex hull of the mesh
    UR5 forearm                                     -> CoACD convex decomposition (32 hulls, <= 64 vertices,
                                                       concavity threshold 0.02), all pieces in one STL

The STL files keep the units of their source (gripper / mount mm, UR m) so the xacro scales stay the same.
UR meshes: ur_description (BSD-3-Clause, see meshes/collision_convex/ur5/LICENSE_ur_description).

Needs (only to rebuild):  pip install trimesh coacd scipy pyyaml   (and a sourced ROS 2 with ur_description)
Run:  python3 ur5_rh_p12_description/scripts/build_collision_hulls.py
"""
import os
import shutil
import subprocess

import numpy as np
import trimesh
import yaml

PKG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(PKG, 'meshes', 'collision_convex')
UR_LINKS = {'base': 'base', 'shoulder': 'shoulder', 'upper_arm': 'upperarm', 'forearm': 'forearm',
            'wrist_1': 'wrist1', 'wrist_2': 'wrist2', 'wrist_3': 'wrist3'}
DECOMP = {'max_convex_hull': 32, 'max_ch_vertex': 64, 'threshold': 0.02}   # Isaac Sim forearm decomposition


def ur_share():
    prefix = subprocess.check_output(['ros2', 'pkg', 'prefix', 'ur_description'], text=True).strip()
    return os.path.join(prefix, 'share', 'ur_description')


def hull(src, dst):
    m = trimesh.load(src)
    h = m.convex_hull
    h.export(dst)
    return len(m.faces), len(h.faces)


def decompose(src, dst):
    import coacd
    coacd.set_log_level('error')
    m = trimesh.load(src)
    parts = coacd.run_coacd(coacd.Mesh(m.vertices, m.faces), threshold=DECOMP['threshold'],
                            max_convex_hull=DECOMP['max_convex_hull'], max_ch_vertex=DECOMP['max_ch_vertex'],
                            decimate=True, preprocess_mode='auto', seed=0)
    hulls = [trimesh.Trimesh(v, f).convex_hull for v, f in parts]
    trimesh.util.concatenate(hulls).export(dst)
    return len(m.faces), len(hulls), max(len(h.vertices) for h in hulls)


def main():
    for d in ('rh_p12_rn_a', 'mount', 'ur5'):
        os.makedirs(os.path.join(OUT, d), exist_ok=True)
    report = []
    for n in ('base', 'r1', 'r2', 'l1', 'l2'):
        f0, f1 = hull(os.path.join(PKG, 'meshes', 'rh_p12_rn_a', f'{n}.stl'), os.path.join(OUT, 'rh_p12_rn_a', f'{n}.stl'))
        report.append(f'gripper {n}: {f0} -> {f1} faces (hull)')
    f0, f1 = hull(os.path.join(PKG, 'meshes', 'mount', 'wrist_mount_collision_plate.stl'),
                  os.path.join(OUT, 'mount', 'wrist_mount_collision_plate.stl'))
    report.append(f'wrist mount plate: {f0} -> {f1} faces (hull)')

    share = ur_share()
    for link, name in UR_LINKS.items():
        src = os.path.join(share, 'meshes', 'ur5', 'collision', f'{name}.stl')
        dst = os.path.join(OUT, 'ur5', f'{name}.stl')
        if link == 'forearm':
            f0, n, v = decompose(src, dst)
            report.append(f'ur5 {name}: {f0} faces -> {n} convex pieces, max {v} vertices (decomposition)')
        else:
            f0, f1 = hull(src, dst)
            report.append(f'ur5 {name}: {f0} -> {f1} faces (hull)')
    lic = next((p for p in (os.path.join(share, 'LICENSE'), '/usr/share/doc/ros-jazzy-ur-description/copyright')
                if os.path.isfile(p)), None)
    if lic is None:
        raise SystemExit('ur_description license text not found (LICENSE or Debian copyright)')
    shutil.copy(lic, os.path.join(OUT, 'ur5', 'LICENSE_ur_description'))

    # ur_description visual parameters with the collision meshes swapped
    with open(os.path.join(share, 'config', 'ur5', 'visual_parameters.yaml')) as f:
        vp = yaml.safe_load(f)
    for link, name in UR_LINKS.items():
        vp['mesh_files'][link]['collision']['mesh'] = {
            'package': 'ur5_rh_p12_description', 'path': f'meshes/collision_convex/ur5/{name}.stl'}
    out_yaml = os.path.join(PKG, 'config', 'ur5_visual_parameters_convex.yaml')
    with open(out_yaml, 'w') as f:
        f.write('# Generated by scripts/build_collision_hulls.py from ur_description config/ur5/visual_parameters.yaml:\n'
                '# same visuals, collision meshes = convex hulls / forearm decomposition (as Isaac Sim). Do not edit.\n')
        yaml.safe_dump(vp, f, sort_keys=False)
    print('\n'.join(report))
    print(f'[OK] {OUT}\n[OK] {out_yaml}')


if __name__ == '__main__':
    main()
